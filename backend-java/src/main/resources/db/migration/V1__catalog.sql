-- V1: каталог — ингредиенты, рецепты, категории.

CREATE TABLE ingredients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    normalized_name VARCHAR(200) NOT NULL,
    default_unit VARCHAR(20) NOT NULL,
    category VARCHAR(100),
    CONSTRAINT uq_ingredients_normalized_name UNIQUE (normalized_name)
);

CREATE TABLE recipes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    image_url VARCHAR(500),
    servings INTEGER NOT NULL,
    cook_time_minutes INTEGER NOT NULL,
    calories DOUBLE PRECISION,
    protein DOUBLE PRECISION,
    fat DOUBLE PRECISION,
    carbs DOUBLE PRECISION,
    diet VARCHAR(30) NOT NULL,
    meal_type VARCHAR(20),
    steps TEXT,
    published BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_recipes_name UNIQUE (name)
);

CREATE TABLE recipe_ingredients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    unit VARCHAR(20) NOT NULL,
    CONSTRAINT uq_recipe_ingredient UNIQUE (recipe_id, ingredient_id),
    CONSTRAINT fk_recipe_ingredients_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipes(id) ON DELETE CASCADE,
    CONSTRAINT fk_recipe_ingredients_ingredient
        FOREIGN KEY (ingredient_id) REFERENCES ingredients(id)
);

CREATE INDEX ix_recipe_ingredients_recipe_id ON recipe_ingredients(recipe_id);
CREATE INDEX ix_recipe_ingredients_ingredient_id ON recipe_ingredients(ingredient_id);

CREATE TABLE recipe_tags (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id INTEGER NOT NULL,
    tag VARCHAR(50) NOT NULL,
    CONSTRAINT uq_recipe_tag UNIQUE (recipe_id, tag),
    CONSTRAINT fk_recipe_tags_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipes(id) ON DELETE CASCADE
);

CREATE INDEX ix_recipe_tags_recipe_id ON recipe_tags(recipe_id);

CREATE TABLE recipe_appliances (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id INTEGER NOT NULL,
    appliance VARCHAR(50) NOT NULL,
    CONSTRAINT uq_recipe_appliance UNIQUE (recipe_id, appliance),
    CONSTRAINT fk_recipe_appliances_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipes(id) ON DELETE CASCADE
);

CREATE INDEX ix_recipe_appliances_recipe_id ON recipe_appliances(recipe_id);

CREATE TABLE recipe_categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(100) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_recipe_categories_name UNIQUE (name),
    CONSTRAINT uq_recipe_categories_slug UNIQUE (slug)
);

CREATE TABLE recipe_category_links (
    recipe_id INTEGER NOT NULL,
    category_id INTEGER NOT NULL,
    PRIMARY KEY (recipe_id, category_id),
    CONSTRAINT fk_rcl_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipes(id) ON DELETE CASCADE,
    CONSTRAINT fk_rcl_category
        FOREIGN KEY (category_id) REFERENCES recipe_categories(id) ON DELETE CASCADE
);
