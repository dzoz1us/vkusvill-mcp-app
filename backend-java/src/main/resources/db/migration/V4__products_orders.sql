-- V4: товары ВкусВилл, заказы, статусы заказов и уведомления.

CREATE TABLE product_mappings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id INTEGER NOT NULL,
    product_xml_id VARCHAR(100) NOT NULL,
    product_name VARCHAR(300) NOT NULL,
    product_url VARCHAR(500),
    package_quantity DOUBLE PRECISION,
    package_unit VARCHAR(20),
    last_price DOUBLE PRECISION,
    match_score DOUBLE PRECISION NOT NULL,
    match_status VARCHAR(30) NOT NULL,
    last_checked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sold_by_weight BOOLEAN NOT NULL DEFAULT FALSE,
    piece_weight_g DOUBLE PRECISION,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_mapping_ingredient UNIQUE (ingredient_id),
    CONSTRAINT fk_product_mappings_ingredient
        FOREIGN KEY (ingredient_id) REFERENCES ingredients(id) ON DELETE CASCADE
);

CREATE TABLE mcp_product_cache (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query VARCHAR(300) NOT NULL,
    response_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_mcp_product_cache_query ON mcp_product_cache(query);

CREATE TABLE order_statuses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    title VARCHAR(100) NOT NULL,
    description VARCHAR(300),
    sort_order INTEGER NOT NULL,
    is_final BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_order_statuses_code UNIQUE (code)
);

