-- V3: планы меню, блюда в плане и список покупок.

CREATE TABLE meal_plans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    title VARCHAR(200),
    saved BOOLEAN NOT NULL DEFAULT FALSE,
    people_count INTEGER NOT NULL,
    budget DOUBLE PRECISION NOT NULL,
    days_json TEXT NOT NULL,
    preferences_json TEXT NOT NULL,
    appliances_json TEXT NOT NULL,
    diet VARCHAR(30) NOT NULL,
    cart_estimated_cost DOUBLE PRECISION NOT NULL,
    unresolved_items_count INTEGER NOT NULL,
    omitted_meals INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL,
    random_seed INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_meal_plans_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX ix_meal_plans_user_id ON meal_plans(user_id);

-- В один приём пищи можно добавить несколько блюд, у блюда свои порции.
CREATE TABLE meal_plan_meals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_plan_id INTEGER NOT NULL,
    day VARCHAR(10) NOT NULL,
    meal_type VARCHAR(20) NOT NULL,
    recipe_id INTEGER NOT NULL,
    servings INTEGER,
    sort_index INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_meal_plan_meals_plan
        FOREIGN KEY (meal_plan_id) REFERENCES meal_plans(id) ON DELETE CASCADE,
    CONSTRAINT fk_meal_plan_meals_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipes(id)
);

CREATE INDEX ix_meal_plan_meals_meal_plan_id ON meal_plan_meals(meal_plan_id);
CREATE INDEX ix_meal_plan_meals_recipe_id ON meal_plan_meals(recipe_id);

CREATE TABLE grocery_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_plan_id INTEGER NOT NULL,
    ingredient_id INTEGER,
    product_name VARCHAR(200) NOT NULL,
    needed_quantity DOUBLE PRECISION NOT NULL,
    needed_unit VARCHAR(20) NOT NULL,
    product_xml_id VARCHAR(100),
    product_url VARCHAR(500),
    package_quantity DOUBLE PRECISION,
    package_unit VARCHAR(20),
    package_count INTEGER,
    price_per_package DOUBLE PRECISION,
    total_price DOUBLE PRECISION,
    match_status VARCHAR(30) NOT NULL,
    is_bought BOOLEAN NOT NULL,
    is_manual BOOLEAN NOT NULL,
    sold_by_weight BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_grocery_items_meal_plan
        FOREIGN KEY (meal_plan_id) REFERENCES meal_plans(id) ON DELETE CASCADE,
    CONSTRAINT fk_grocery_items_ingredient
        FOREIGN KEY (ingredient_id) REFERENCES ingredients(id) ON DELETE SET NULL
);

CREATE INDEX ix_grocery_items_meal_plan_id ON grocery_items(meal_plan_id);
CREATE INDEX ix_grocery_items_ingredient_id ON grocery_items(ingredient_id);
